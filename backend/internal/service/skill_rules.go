// shortDramaSkillDoc 是原始的短剧 H3 提示词生产规范（short-drama-h3-prompt skill）。
//
// 原样嵌进二进制，一是留档方便对照，二是以后要扩规则可以直接改这个 md。
// 注意：不会把全文塞给 LLM —— 里面有大量 H3 六段式（英文）的写法，
// 而本项目的视频提示词是中文描述词，六段式由工作流里的 Qwen H3 Prompt 节点负责转换，
// 两套格式同时给模型只会打架。真正注入的是下面 storyboardSkillRules 里提炼的规则。
//
//go:embed prompts/short-drama-h3-prompt.md
var shortDramaSkillDoc string

// ShortDramaSkillDoc 返回规范原文（给管理端/调试看，不参与生成）
func ShortDramaSkillDoc() string { return shortDramaSkillDoc }

// storyboardSkillRules 从 short-drama-h3-prompt 提炼出的、与「生成分镜」直接相关的规范。
//
// 挑选标准：只保留能落到分镜结构（段/镜头/台词/站位）上的规则，
// 纯 H3 英文格式、参考图 Picture 编号这些由工作流或前端负责的不放进来。
const storyboardSkillRules = `

【短剧生产规范】（来自 short-drama-h3-prompt skill，必须遵守）

一、语速与时长
- 语速 = 台词汉字数 ÷（镜头时长 − 气口总时长 − 纯动作时长），标点不计入字数
- 台词里的每个「——」算 0.8 秒气口，计算语速时必须从时长里扣掉
- 语速参考：正常对话 3–4.5 字/秒；高冷/淡定 2.5–4；撒娇/害羞 2–3.5；激动/快说 4.5–6
- 铁律：禁止出现 5 字/秒以上还叠加气口。说不完就加镜头或加段，绝不硬挤

二、节奏
- 每段第 4 秒必须进入对话，开头不要拖在动作和环境上
- 纯动作/环境镜头不超过 3 秒
- 段与段要接得上：上一段结尾的钩子 → 下一段开头承接

三、位置锁定（人物跑位是第二大问题）
- 桌子/房间布局是空间锚点：写清谁坐哪一侧、桌子在谁和谁之间、椅子在哪
- 位置整集不变；动作里明确「不起身、不离开座位、不绕桌走动」
- 多人场景优先中景/中近景，少用全景 —— 全景最容易把座位排错
- 人物位置写进 situation 和 locking，不要只写一次

三之二、朝向锁定（和位置同等重要，最容易漏）
- 只写左右不写朝向 = 两人各看各的：生成出来说话人正对镜头念台词，像在跟观众说话
- 两人同处一室必须写「隔着桌子相对而坐、身体互相朝向、视线交汇」
- 每个说话镜头都要有视线落点：「看向 @对方」，不能写「抬眼看」这种没有落点的
- 单人镜头（中近景/近景/特写）必须写「侧脸或四分之三侧脸朝向 @对方」，禁止正面朝镜头

四、人物锁定（一致性高于一切）
- 服装拆成具体部件写（领型/袖长/扣型/下装长度/鞋），禁止「穿得正式」这种模糊词
- 发型写清并否定不需要的特征（如「顶部发量厚，不秃顶、不发际线后退」）
- 音色按角色绑定，整集不变
- 这三项在 situation 里不重复写（有单独的锁定块），但要保证与锁定块一致

五、说话镜头锁人
- 谁说话，镜头锁谁，不要切到别人 —— 否则模型会让错的人动嘴
- 长台词要给足时间说完再切下一镜
- 必须在 A 说话时展示 B 的反应，就用 A 的过肩镜头（A 在前景、B 在后），动嘴的仍是 A

六、动作归属
- 每个动作必须明确是谁做的，不要写「松了口气」这种没主语的句子
- 动作要挂在对应的那个镜头上，不要跨镜头堆动作`

// StoryboardSkillRules 返回注入分镜 system prompt 的生产规范
func StoryboardSkillRules() string {
	return strings.TrimRight(storyboardSkillRules, "\n")
}
